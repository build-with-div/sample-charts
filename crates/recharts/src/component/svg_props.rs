//! `util/svgPropertiesNoEvents.js`: which props Recharts passes on to the
//! SVG elements it renders.

use crate::dom::Props;

/// `isSvgElementPropKey`: `SVGElementPropKeys` (301 names; `type` is left
/// out on purpose there).
pub(crate) fn is_svg_element_prop_key(key: &str) -> bool {
    SVG_ELEMENT_PROP_KEYS.contains(&key)
}

/// `isDataAttribute`.
pub(crate) fn is_data_attribute(key: &str) -> bool {
    key.starts_with("data-")
}

/// `svgPropertiesNoEvents(obj)`: the SVG props and `data-` attributes.
///
/// `svgPropertiesAndEvents` also keeps event handlers; a handler sets no
/// attribute, so for the DOM this module builds the two filters agree and
/// this one serves for both.
pub(crate) fn svg_properties(props: &Props) -> Props {
    props.filter(|key| is_svg_element_prop_key(key) || is_data_attribute(key))
}

